"""User-defined model connections. Credentials never enter YAML or chat journals."""
from __future__ import annotations

import copy
import hashlib
import json
import os
import re
from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass, field
from urllib.parse import urlsplit

import yaml
from core.paths import APP_PATHS

PROTOCOLS = {'chat_completions', 'responses', 'anthropic_messages', 'gemini'}
_bound = ContextVar('model_connection', default=None)
_runtime_keys = {}
_SERVICE = 'Toshy model connections'


def _read_config():
    with open(APP_PATHS.config, encoding='utf-8') as handle:
        config = yaml.safe_load(handle) or {}
    if not isinstance(config, dict):
        raise ValueError('Application configuration must be a mapping.')
    return config


def load_settings():
    return _settings_from_config(_read_config())


def _settings_from_config(config):
    settings = copy.deepcopy(config.get('model_api') or {})
    settings.setdefault('mode', 'local')
    settings.setdefault('local_url', (config.get('llm') or {}).get('api_url', ''))
    settings.setdefault('local_model', (config.get('llm') or {}).get('model_name', ''))
    settings.setdefault('connections', [])
    # Preserve explicitly configured older single-local connections, while a
    # fresh installation starts with an empty connections list.
    if (settings.get('profile_schema') != 2 and not settings['connections']
            and settings['mode'] != 'api' and settings.get('local_url') and settings.get('local_model')
            and (str(settings['local_url']).rstrip('/') != 'http://localhost:8080/v1'
                 or settings['local_model'] != 'local-agent-core')):
        settings['connections'].append({'id': 'local-default', 'name': 'Local model', 'mode': 'local',
            'base_url': settings['local_url'], 'model': settings['local_model'],
            'protocol': 'chat_completions', 'require_key': False})
        settings.setdefault('selected', 'local-default')
    # Connections are user-defined. Do not manufacture a local-model preset.
    # Remove only the untouched factory record generated by older versions;
    # edited profiles (including their endpoint/model/options) are preserved.
    factory_fields = {'id', 'name', 'mode', 'base_url', 'model', 'protocol', 'require_key'}
    removed = set()
    connections = []
    for record in settings['connections']:
        factory = (re.fullmatch(r'local-default(?:-legacy)*', str(record.get('id', '')))
            and record.get('name') in {'Local model', 'Локальная модель'}
            and record.get('mode', 'local') == 'local'
            and str(record.get('base_url', '')).rstrip('/') == 'http://localhost:8080/v1'
            and record.get('model') == 'local-agent-core'
            and record.get('protocol', 'chat_completions') == 'chat_completions'
            and not record.get('require_key', False)
            and not (set(record) - factory_fields))
        if factory:
            removed.add(record['id'])
        else:
            connections.append(record)
    settings['connections'] = connections
    if settings.get('selected') in removed:
        settings['selected'] = None
    settings['profile_schema'] = 2
    for record in settings['connections']:
        record.setdefault('mode', 'api')
    return settings


def _write_settings(config, settings, *, validate=True):
    from core.private_files import atomic_private
    clean = copy.deepcopy(settings)
    for name in ('mode', 'local_url', 'local_model'):
        clean.pop(name, None)
    clean['profile_schema'] = 2
    for connection in clean.get('connections', []):
        connection.pop('api_key', None)
        if validate:
            validate_connection(connection, allow_empty=True)
    if not clean.get('connections'):
        clean['connections'] = []
        clean['selected'] = None
    config['model_api'] = clean
    # Other llm parameters may still be used by custom modules. Only the two
    # superseded single-model fields belong to this migration.
    llm = config.get('llm')
    if isinstance(llm, dict):
        llm.pop('api_url', None)
        llm.pop('model_name', None)
        if not llm:
            config.pop('llm', None)
    atomic_private(APP_PATHS.config, yaml.safe_dump(config, allow_unicode=True, sort_keys=False).encode('utf-8'))
    return clean


def save_settings(settings):
    from core.private_files import file_lock
    path = APP_PATHS.config
    with file_lock(path.with_name(path.name + '.lock')):
        if path.is_symlink():
            raise OSError('Application configuration cannot be a symbolic link.')
        return _write_settings(_read_config(), settings)


def remove_connection(connection_id):
    """Persist one removal without committing unrelated unsaved GUI drafts."""
    from core.private_files import file_lock
    path = APP_PATHS.config
    with file_lock(path.with_name(path.name + '.lock')):
        if path.is_symlink():
            raise OSError('Application configuration cannot be a symbolic link.')
        config = _read_config()
        settings = _settings_from_config(config)
        settings['connections'] = [item for item in settings['connections'] if item.get('id') != connection_id]
        known = {item['id'] for item in settings['connections']}
        if settings.get('selected') not in known:
            settings['selected'] = settings['connections'][0]['id'] if settings['connections'] else None
        clean = _write_settings(config, settings, validate=False)
    remember_runtime_key(connection_id, '')
    return clean


def validate_connection(connection, allow_empty=False):
    if connection.get('provider'):
        from core.model_providers import providers
        provider = providers().get(connection['provider'])
        if provider is not None:
            connection = provider.configure(copy.deepcopy(connection))
    url = str(connection.get('base_url') or '').strip().rstrip('/')
    if url or not allow_empty:
        parsed = urlsplit(url)
        if parsed.scheme not in {'http', 'https'} or not parsed.hostname or parsed.username or parsed.password:
            raise ValueError('Укажите HTTP(S) URL API без логина и пароля в адресе.')
        if parsed.query or parsed.fragment:
            raise ValueError('URL API должен быть базовым адресом без параметров и фрагмента.')
    if connection.get('mode', 'api') not in {'local', 'api'}:
        raise ValueError('Неизвестный тип подключения.')
    if connection.get('protocol', 'chat_completions') not in PROTOCOLS:
        raise ValueError('Неизвестный протокол API.')
    if not allow_empty and not str(connection.get('model') or '').strip():
        raise ValueError('Укажите имя модели из кабинета провайдера или списка моделей.')
    from core.model_compatibility import validate_options
    validate_options(connection)
    for key in ('extra_body', 'extra_headers'):
        value = connection.get(key) or {}
        if key == 'extra_body' and any(name in value for name in ('model', 'messages', 'input', 'tools', 'stream', 'store', 'previous_response_id', 'contents', 'systemInstruction', 'system', 'stream_options')):
            raise ValueError('Модель, сообщения, инструменты и поток задаются транспортом, не дополнительным JSON.')
        if not isinstance(value, dict):
            raise ValueError(f'{key}: нужен JSON-объект.')
        def check(data):
            if isinstance(data, dict):
                for name, item in data.items():
                    if any(word in str(name).lower() for word in ('authorization', 'api_key', 'api-key', 'password', 'secret')):
                        raise ValueError('Секреты вводите в поле ключа, а не в дополнительные параметры.')
                    check(item)
            elif isinstance(data, list):
                for item in data:
                    check(item)
        check(value)
    if connection.get('auth_header') and ('\n' in connection['auth_header'] or '\r' in connection['auth_header']):
        raise ValueError('Некорректное имя заголовка авторизации.')
    return url


def remember_runtime_key(connection_id, key):
    if key:
        _runtime_keys[str(connection_id)] = str(key)
    else:
        _runtime_keys.pop(str(connection_id), None)


def _secure_keyring():
    import keyring
    backend = keyring.get_keyring()
    candidates = getattr(backend, 'backends', None) or [backend]
    for candidate in candidates:
        if type(candidate).__module__.startswith(('keyring.backends.Windows', 'keyring.backends.SecretService', 'keyring.backends.kwallet', 'keyring.backends.macOS')):
            from release_tools.credentials import track
            return track(candidate)
    raise RuntimeError('Защищённое хранилище ОС недоступно. Используйте переменную окружения или ключ до закрытия приложения.')


def store_key(connection_id, key):
    """OS credential store only; never fall back to a plaintext keyring backend."""
    import keyring
    backend = _secure_keyring()
    if key:
        backend.set_password(_SERVICE, str(connection_id), key)
    else:
        try:
            backend.delete_password(_SERVICE, str(connection_id))
        except keyring.errors.PasswordDeleteError:
            pass


def resolve_key(connection):
    identity = str(connection.get('id') or '')
    env = str(connection.get('key_env') or '').strip()
    if env:
        return os.environ.get(env, '')
    if identity in _runtime_keys:
        return _runtime_keys[identity]
    if connection.get('key_storage') == 'runtime':
        return ''
    try:
        return _secure_keyring().get_password(_SERVICE, identity) or ''
    except Exception:
        pass
    return ''


@dataclass(frozen=True)
class ModelConnection:
    mode: str
    base_url: str
    model: str
    protocol: str = 'chat_completions'
    options: dict = field(default_factory=dict)
    key: str = field(default='', repr=False, compare=False)

    @property
    def fingerprint(self):
        return hashlib.sha256(json.dumps([self.base_url, self.model, self.protocol], ensure_ascii=False).encode()).hexdigest()

    def headers(self):
        headers = dict(self.options.get('extra_headers') or {})
        if self.protocol == 'anthropic_messages':
            headers.setdefault('anthropic-version', '2023-06-01')
        if self.key:
            default = {'anthropic_messages': 'x-api-key', 'gemini': 'x-goog-api-key'}.get(self.protocol, 'Authorization')
            name = self.options.get('auth_header') or default
            prefix = self.options.get('auth_prefix', '' if default in {'x-api-key', 'x-goog-api-key'} else 'Bearer ')
            headers[name] = prefix + self.key
        return headers


def snapshot(fallback_url='', fallback_model='', *, allow_missing_model=False, connection_id=None):
    bound = _bound.get()
    if bound is not None and connection_id is None:
        return bound
    config = _read_config()
    settings = _settings_from_config(config)
    identity = connection_id if connection_id is not None else settings.get('selected')
    connection = next((item for item in settings['connections'] if item.get('id') == identity), None)
    if connection is None:
        if (not identity and not settings['connections']
                and (config.get('model_api') or {}).get('profile_schema') != 2):
            return ModelConnection('local', fallback_url.rstrip('/'), fallback_model)
        raise ValueError('Model profile is unavailable. Select a profile in chat or configure a default profile in API settings.')
    from core.model_providers import provider_for
    provider = provider_for(connection)
    if provider is not None:
        connection = provider.configure(copy.deepcopy(connection))
    check = dict(connection)
    if allow_missing_model and not check.get('model'):
        check['model'] = 'catalog'
    url = validate_connection(check)
    mode = connection.get('mode', 'api')
    key = resolve_key(connection) if mode == 'api' else ''
    if mode == 'api' and connection.get('require_key', True) and not key:
        raise ValueError('Ключ API не задан или переменная окружения недоступна процессу ядра.')
    return ModelConnection(mode, url, str(connection.get('model') or '').strip(),
                           connection.get('protocol', 'chat_completions') if mode == 'api' else 'chat_completions',
                           copy.deepcopy(connection), key)


def push_runtime_keys(clear=(), *, connection_id=None):
    """GUI and core are separate processes. Transfer ephemeral keys over the
    authenticated loopback API; retries happen before the next generation."""
    known = {item['id'] for item in load_settings()['connections']}
    keys = {identity: key for identity, key in _runtime_keys.items()
            if identity in known and (connection_id is None or identity == connection_id)}
    if not keys and not clear:
        return
    from core.security import auth_headers
    import httpx
    with httpx.Client(trust_env=False, timeout=5) as client:
        response = client.post('http://127.0.0.1:5000/v1/model/credentials',
                               json={'keys': keys, 'clear': list(clear)}, headers=auth_headers())
        response.raise_for_status()


@contextmanager
def bind_model_connection(connection):
    token = _bound.set(connection)
    try:
        yield connection
    finally:
        _bound.reset(token)
